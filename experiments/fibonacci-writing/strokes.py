def script_paths():
    paths = []
    for row, line in enumerate(CODE.splitlines()):
        for col, ch in enumerate(line):
            if ch == " ":
                continue
            for stroke in GLYPHS[ch]:
                xy = np.array(stroke)
                yz = np.c_[
                    -0.015 - (col + xy[:, 0]) * 0.015,
                    1.115 - row * 0.085 + xy[:, 1] * 0.035,
                ]
                paths.append((row, ch, yz))
    return paths


